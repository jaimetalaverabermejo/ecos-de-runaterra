import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const server = await createServer({ server: { middlewareMode: true }, optimizeDeps: { noDiscovery: true } });
try {
  const {DataRegistry:D} = await server.ssrLoadModule('/src/data/DataRegistry.ts');
  const {WorldActionService:W} = await server.ssrLoadModule('/src/systems/world/WorldActionService.ts');
  const {QuestTrackingService:T} = await server.ssrLoadModule('/src/systems/quests/QuestTrackingService.ts');
  const {SaveService:S} = await server.ssrLoadModule('/src/systems/save/SaveService.ts');
  const {ConditionService:C} = await server.ssrLoadModule('/src/systems/world/ConditionService.ts');
  const {createNewGame} = await server.ssrLoadModule('/src/state/GameState.ts');
  let s = createNewGame();
  const talk = id => { const d=D.dialogue(id); let node=d.nodes.find(n=>n.id===d.startNodeId); while(node){ W.applyAll(s,node.actions); node=d.nodes.find(n=>n.id===node.nextNodeId); } };
  for (const id of ['ionia-karma-suyin-opening','ionia-karma-pagoda-invitation','ionia-karma-intro','ionia-karma-keeper','ionia-karma-tao','ionia-karma-stone','ionia-karma-inscription']) talk(id);
  const quiz = D.dialogue('ionia-karma-memory-scene');
  assert.equal(quiz.nodes[0].choices.length, 3);
  const date = quiz.nodes[0].choices[0].label;
  assert(D.dialogue('ionia-karma-inscription').nodes[0].lines.some(l=>l.includes(date)), 'The exact answer must be visible on the wall');
  W.applyAll(s, quiz.nodes[0].choices[1].actions);
  assert(s.worldProgress.flags.includes('story:karma-date-recheck'), 'Closing the wrong-answer dialogue early must still require rereading');
  W.applyAll(s, quiz.nodes.find(n=>n.id==='error').actions);
  assert(!s.worldProgress.flags.includes('story:ionia-karma-flashback'));
  assert(T.next(s,'ionia-karma-memory').includes('comprueba la fecha'));
  const k = D.npc('ionia-karma-intro');
  assert.equal(k.dialogueVariants.find(v=>C.matchesAll(s,v.conditions)).dialogueId,'ionia-karma-date-recheck');
  s = S.deserializeSave(JSON.stringify(s));
  assert(s.worldProgress.flags.includes('story:karma-date-recheck'));
  talk('ionia-karma-inscription');
  assert(!s.worldProgress.flags.includes('story:karma-date-recheck'));
  assert(quiz.nodes.find(n=>n.id==='recuerdo').actions.some(a=>a.type==='play-story'&&a.storyId==='karma-flashback'));
  const flash=read('src/data/stories/karma-flashback.json');
  assert(flash.beats.every(b=>b.grayscale));
  assert.equal(flash.returnDialogueId,'ionia-karma-resolution');
  W.applyAll(s,flash.completionActions);
  const invitation=D.dialogue('ionia-karma-resolution');
  W.applyAll(s,invitation.nodes[0].choices[1].actions);
  W.applyAll(s,invitation.nodes.find(n=>n.id==='nombres').actions);
  assert(!invitation.nodes.some(n=>n.actions?.some(a=>a.type==='play-story')));
  assert(s.worldProgress.flags.includes('story:karma-memorial-journey'));
  assert.equal(s.quests['ionia-karma-memory'].status,'active');
  for(const id of ['karma','meilin','tao'])assert(C.matchesAll(s,D.npc('ionia-karma-memorial-'+id).conditions));
  talk('ionia-karma-memorial-meilin');talk('ionia-karma-memorial-tao');
  const before=s.gold;talk('ionia-karma-memorial-world');
  assert.equal(s.quests['ionia-karma-memory'].status,'completed');
  assert.equal(s.gold,before+180);
  talk('ionia-karma-memorial-world');assert.equal(s.gold,before+180);
  s=S.deserializeSave(JSON.stringify(s));assert(s.worldProgress.flags.includes('story:karma-departed'));
  assert(!C.matchesAll(s,D.npc('ionia-karma-intro').conditions));
  assert(!T.entries(s).some(q=>q.id==='ionia-karma-memory'));
  const def=D.map('jo05_placidium'),map=read('public/'+def.tiled.url.replace('./',''));
  for(const id of ['karma-stone','karma-inscription']){
    const o=map.layers.find(l=>l.name==='Interactions').objects.find(o=>o.name===id);
    const p=Object.fromEntries(o.properties.map(p=>[p.name,p.value]));
    assert.equal(p.resolvedFlag,'story:ionia-karma-arc-resolved');
    assert.equal(p.resolvedDialogueId,'ionia-karma-stone-after');
  }
  const exit=map.layers.find(l=>l.name==='Portals').objects.find(o=>o.name==='to_estuary');
  const paths=map.layers.find(l=>l.name==='Paths').data;
  assert.equal(exit.x,def.width-32);
  assert.equal(exit.height,64);
  for(let y=exit.y;y<exit.y+exit.height;y+=32)assert(paths[(y/32)*map.width+exit.x/32], 'Every eastbound trail lane must enter the portal');
  const arrival=map.layers.find(l=>l.name==='Spawns').objects.find(o=>o.name==='from_next');
  assert(arrival.x<exit.x-16,'Return spawn must not bounce straight back to the Estuary');
  assert.equal(arrival.y,def.spawns.from_next.y);
  console.log('Karma: visible date, wrong-answer reread/reload gate, memory-only scene, physical gathering, single reward, persistent restored wall, tracker and both eastbound trail lanes: OK.');
} finally { await server.close(); }
